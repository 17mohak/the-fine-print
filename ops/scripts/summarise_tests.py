#!/usr/bin/env python3
"""Summarise Gradle JUnit XML results for the graded modules into a Markdown report.

Usage: ./gradlew :cia:cia-algorithms:test :cia:cia-bench:test :cia:cia-demo:test
       python ops/scripts/summarise_tests.py > docs/cia/evidence/test-report.md
"""
import glob, os, platform, re, sys, xml.etree.ElementTree as ET

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
files = sorted(glob.glob(os.path.join(ROOT, "cia", "*", "build", "test-results", "test", "*.xml")))
if not files:
    sys.exit("No test results found. Run the Gradle test tasks first.")
tot = fail = skip = 0
out = []
by_mod = {}
for f in files:
    mod = f.replace("\\", "/").split("/cia/")[1].split("/")[0]
    r = ET.parse(f).getroot()
    cases = [(c.get("name"), float(c.get("time", 0)), c.find("failure") is not None or c.find("error") is not None,
              c.find("skipped") is not None) for c in r.iter("testcase")]
    by_mod.setdefault(mod, []).append((r.get("name").rsplit(".", 1)[-1], cases))
    tot += len(cases); fail += sum(1 for c in cases if c[2]); skip += sum(1 for c in cases if c[3])
out.append("# Test report (generated)\n")
out.append(f"Generated by `ops/scripts/summarise_tests.py` from Gradle's JUnit XML. Platform: {platform.system()} {platform.release()}.\n")
out.append(f"**{tot} tests, {fail} failed, {skip} skipped.**\n")
out.append("| Module | Test class | Tests | Failed |\n|---|---|---|---|")
for mod, classes in by_mod.items():
    for cls, cases in classes:
        out.append(f"| {mod} | {cls} | {len(cases)} | {sum(1 for c in cases if c[2])} |")
out.append("")
for mod, classes in by_mod.items():
    out.append(f"## {mod}\n")
    for cls, cases in classes:
        out.append(f"**{cls}**\n")
        for name, t, bad, sk in cases:
            out.append(f"- {'FAIL' if bad else 'pass'} `{re.sub(r'[()]+$', '', name)}`")
        out.append("")
print("\n".join(out))
sys.exit(1 if fail else 0)
